# 5.6. Stage of Life

age = 27

if age < 2:
    print(f"\nThis person is just a baby.\n")
elif age >= 2 and age < 4:
    print(f"\nThis person is a toddler.\n")
elif age >= 4 and age < 13:
    print(f"\nThis person is a kid.\n")
elif age >= 13 and age < 20:
    print(f"\nThis person is a teenager.\n")
elif age >= 20 and age < 65:
    print(f"\nThis person is an adult.\n")
elif age >= 65:
    print(f"\nThis person is an elder.\n")